internal sealed record RepairTool(string Id, int Group, string German, string English, string Executable,
    string Arguments, bool OpensWindow, bool IsRepair, string[] De, string[] En)
{
    internal string? ReportFolder => Id switch
    {
        "check" => "DISM-Schnellpruefung",
        "scan" => "DISM-Tiefenpruefung",
        "verify" => "Systemdateien-pruefen",
        "disk" => "Dateisystem-pruefen",
        "storage-health" => "Laufwerkszustand",
        "driver-packages" => "Treiberpakete",
        "device-problems" => "Geraete-mit-Fehlercode",
        "system-events" => "Windows-Systemfehler",
        "network-diagnostics" => "Netzwerkdiagnose",
        "network-services" => "Netzwerkdienste",
        "winsock-reset" => "Winsock-Reset",
        "tcpip-reset" => "TCP-IP-Reset",
        "dns" => "DNS-Cache-leeren",
        "dns-servers" => "DNS-Server",
        "dhcp-renew" => "DHCP-Adresse-erneuern",
        "adapter-restart" => "Netzwerkadapter-neu-starten",
        "reliability" => "Zuverlaessigkeitsverlauf",
        _ => null
    };

    internal bool NeedsAdapter => Id is "dns-servers" or "dhcp-renew" or "adapter-restart";
    internal bool IsNetworkReset => Id is "winsock-reset" or "tcpip-reset";
    internal bool IsNetworkAction => NeedsAdapter || Id == "dns" || IsNetworkReset;
    internal bool UsesLocalizedQuery => IsNetworkAction || Id is "network-diagnostics" or "network-services" or "storage-health" or "driver-packages";
    internal bool ShowsDiagnosticOutput => UsesLocalizedQuery || Id is "device-problems" or "system-events";
    internal bool IsReset => Id is "update-reset" or "update-dism";
    internal string Title(bool english) => english ? English : German;
    internal string Command => IsReset
        ? (Id == "update-dism" ? RepairUpdateReset.WithDism : RepairUpdateReset.Script)
        : Executable == "powershell.exe" ? Arguments
        : (OpensWindow ? Executable == "control.exe" ? "control" : Executable : Path.GetFileNameWithoutExtension(Executable))
            + (Arguments.Length == 0 ? "" : " " + Arguments);
    internal string CommandFor(bool english, RepairNetworkRequest? network = null) => UsesLocalizedQuery
        ? (english ? "$english = $true" : "$english = $false") + Environment.NewLine +
            "function Label($de, $en) { if ($english) { $en } else { $de } }" + Environment.NewLine +
            (NeedsAdapter && network is not null ? network.Prelude(Id) + Environment.NewLine : "") + Arguments
        : Command;
    internal string Caption => Id switch
    {
        "device-problems" => Executable == "powershell.exe" ? "Get-CimInstance" : "PnPUtil · /problem",
        "system-events" => "Get-WinEvent",
        "network-diagnostics" => "IP · Gateway · DNS",
        "network-services" => "Get-Service",
        "winsock-reset" => "netsh winsock reset",
        "tcpip-reset" => "netsh int ip reset",
        "dns" => "Clear-DnsClientCache",
        "dns-servers" => "Set-DnsClientServerAddress",
        "dhcp-renew" => "RenewDHCPLease",
        "adapter-restart" => "Restart-NetAdapter",
        "storage-health" => "Get-PhysicalDisk",
        "driver-packages" => "Get-WindowsDriver",
        "update-reset" => "Windows Update",
        "update-dism" => "Windows Update + DISM",
        _ => Command
    };

    private const string DeviceProblemQuery = """
        Get-CimInstance Win32_PnPEntity -Filter 'Present = TRUE AND ConfigManagerErrorCode <> 0' -ErrorAction Stop |
            ForEach-Object { '{0} | Code {1} | {2}' -f $_.Name, $_.ConfigManagerErrorCode, $_.PNPDeviceID }
        """;

    private const string SystemEventQuery = """
        try {
            $events = Get-WinEvent -FilterHashtable @{ LogName = 'System'; Level = 1,2 } -MaxEvents 20 -ErrorAction Stop
        } catch {
            if ($_.FullyQualifiedErrorId -notlike 'NoMatchingEventsFound,*') { throw }
            $events = @()
        }
        foreach ($event in $events) {
            $message = ([string]$event.Message -replace '\s+', ' ').Trim()
            if ($message.Length -gt 400) { $message = $message.Substring(0, 400) + '…' }
            '{0:yyyy-MM-dd HH:mm:ss} | {1} | {2} {3}' -f $event.TimeCreated, $event.LevelDisplayName, $event.ProviderName, $event.Id
            if ($message) { $message }
            ''
        }
        """;


